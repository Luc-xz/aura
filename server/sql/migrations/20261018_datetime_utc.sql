-- 时间列 TIMESTAMP → DATETIME(3)：存量值保持 UTC 语义不变。
-- 执行：mysql -u<user> -p < server/sql/migrations/20261018_datetime_utc.sql
-- 幂等：MODIFY 对已达标的列是无操作，可重复执行。

USE `aura`;

SET time_zone = '+00:00';

ALTER TABLE user
  MODIFY created_at DATETIME(3) DEFAULT CURRENT_TIMESTAMP(3),
  MODIFY updated_at DATETIME(3) DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3);

ALTER TABLE role
  MODIFY created_at DATETIME(3) DEFAULT CURRENT_TIMESTAMP(3),
  MODIFY updated_at DATETIME(3) DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3);

ALTER TABLE user_role
  MODIFY created_at DATETIME(3) DEFAULT CURRENT_TIMESTAMP(3),
  MODIFY updated_at DATETIME(3) DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3);

ALTER TABLE menu
  MODIFY created_at DATETIME(3) DEFAULT CURRENT_TIMESTAMP(3),
  MODIFY updated_at DATETIME(3) DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3);

ALTER TABLE role_menu
  MODIFY created_at DATETIME(3) DEFAULT CURRENT_TIMESTAMP(3),
  MODIFY updated_at DATETIME(3) DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3);

ALTER TABLE workspace
  MODIFY created_at DATETIME(3) DEFAULT CURRENT_TIMESTAMP(3),
  MODIFY updated_at DATETIME(3) DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3);

-- idx_chat_workspace_created 依赖 created_at，ALTER 会自动重建该索引，无需单独处理。
ALTER TABLE chat
  MODIFY created_at DATETIME(3) DEFAULT CURRENT_TIMESTAMP(3),
  MODIFY updated_at DATETIME(3) DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3);

ALTER TABLE note
  MODIFY created_at DATETIME(3) DEFAULT CURRENT_TIMESTAMP(3),
  MODIFY updated_at DATETIME(3) DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3);

ALTER TABLE model_config
  MODIFY created_at DATETIME(3) DEFAULT CURRENT_TIMESTAMP(3),
  MODIFY updated_at DATETIME(3) DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3);

ALTER TABLE user_settings
  MODIFY created_at DATETIME(3) DEFAULT CURRENT_TIMESTAMP(3),
  MODIFY updated_at DATETIME(3) DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3);
